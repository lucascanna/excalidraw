/**
 * Generates `packages/excalidraw/components/EmojiPicker/emojiData.ts`, the
 * emoji set of the emoji stamp tool's picker, from Unicode's `emoji-test.txt`
 * (https://unicode.org/Public/emoji/latest/emoji-test.txt).
 *
 * Keeps the fully-qualified emoji of every group but "Component", without the
 * skin-tone variants, with their CLDR short names for search and labels.
 *
 * usage: node scripts/buildEmojiData.js <path to emoji-test.txt>
 *   then format the output with `yarn fix:code`
 */
const fs = require("fs");
const path = require("path");

const GROUP_IDS = {
  "Smileys & Emotion": "smileys",
  "People & Body": "people",
  "Animals & Nature": "animals",
  "Food & Drink": "food",
  "Travel & Places": "travel",
  Activities: "activities",
  Objects: "objects",
  Symbols: "symbols",
  Flags: "flags",
};

const SKIN_TONE = /[\u{1F3FB}-\u{1F3FF}]/u;

const [, , inputPath] = process.argv;
if (!inputPath) {
  console.error("usage: node scripts/buildEmojiData.js <emoji-test.txt>");
  process.exit(1);
}

const source = fs.readFileSync(inputPath, "utf8");
const version = source.match(/^# Version: ([\d.]+)/m)?.[1] ?? "unknown";

const groups = [];
let group = null;

for (const line of source.split("\n")) {
  const groupMatch = line.match(/^# group: (.+)$/);
  if (groupMatch) {
    const id = GROUP_IDS[groupMatch[1].trim()];
    group = id ? { id, emoji: [] } : null;
    if (group) {
      groups.push(group);
    }
    continue;
  }
  if (!group || line.startsWith("#") || !line.trim()) {
    continue;
  }
  // 1F600 ; fully-qualified # 😀 E1.0 grinning face
  const match = line.match(
    /^[0-9A-F ]+;\s*fully-qualified\s*#\s*(\S+)\s+E[\d.]+\s+(.+)$/,
  );
  if (!match) {
    continue;
  }
  const [, emoji, name] = match;
  if (SKIN_TONE.test(emoji)) {
    continue;
  }
  group.emoji.push([emoji, name.trim()]);
}

const outputPath = path.resolve(
  __dirname,
  "../packages/excalidraw/components/EmojiPicker/emojiData.ts",
);

const body = groups
  .map(
    ({ id, emoji }) =>
      `  {\n    id: "${id}",\n    emoji: [\n${emoji
        .map(
          ([char, name]) =>
            `      [${JSON.stringify(char)}, ${JSON.stringify(name)}],`,
        )
        .join("\n")}\n    ],\n  },`,
  )
  .join("\n");

fs.writeFileSync(
  outputPath,
  `// Generated by scripts/buildEmojiData.js from Unicode emoji-test.txt, version ${version}.
// Do not edit by hand.

import type { EmojiGroupData } from "./emojiTypes";

export const EMOJI_GROUPS: readonly EmojiGroupData[] = [
${body}
];
`,
);

console.info(
  `wrote ${groups.reduce((sum, g) => sum + g.emoji.length, 0)} emoji in ${
    groups.length
  } groups (Unicode ${version}) to ${path.relative(process.cwd(), outputPath)}`,
);
